function TrinketDatabase:Get(itemId)
    itemId = tonumber(itemId)
    if not itemId then
        return nil
    end

    local spells = MULTI_PROC_SPELLS_BY_ITEM[itemId]
    local singleSpell = PROC_SPELL_BY_ITEM[itemId]
    if not spells and singleSpell then
        spells = { singleSpell }
    end

    if not spells then
        return nil
    end

    local internalCooldown = ICD_OVERRIDE_BY_ITEM[itemId]
    if internalCooldown == nil then
        internalCooldown = NO_FIXED_ICD[itemId] and 0 or DEFAULT_PROC_ICD
    end

    return {
        itemId = itemId,
        procSpellIds = spells,
        internalCooldown = internalCooldown,
    }
end
